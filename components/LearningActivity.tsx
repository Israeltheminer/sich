"use client";

import { LearningProposal } from "@/lib/sitch/types";

const STEPS = [
  "New interaction received",
  "Communication pattern detected",
  "Pattern evaluated",
  "Guidance updated",
  "New communication profile generated",
];

const CONFIDENCE_STYLE: Record<string, string> = {
  high: "bg-emerald-500/20 text-emerald-300",
  medium: "bg-amber-500/20 text-amber-300",
  low: "bg-white/10 text-white/50",
};

export function LearningActivity({
  proposal,
  loading,
  applying,
  onRun,
  onApply,
  pendingCount,
}: {
  proposal: LearningProposal | null;
  loading: boolean;
  applying: boolean;
  onRun: () => void;
  onApply: () => void;
  pendingCount: number;
}) {
  const litSteps = loading ? 1 : proposal ? (proposal.meaningfulChange ? STEPS.length : 3) : 0;

  return (
    <div className="rounded-2xl border border-white/10 bg-white/[0.03] p-5">
      <div className="flex items-center justify-between">
        <h3 className="font-semibold text-lg">Learning activity</h3>
        <span className="text-xs text-white/40">
          {pendingCount} pending example{pendingCount === 1 ? "" : "s"}
        </span>
      </div>

      <ol className="mt-4 space-y-2">
        {STEPS.map((step, i) => {
          const lit = litSteps > i;
          return (
            <li key={step} className="flex items-center gap-3 text-sm">
              <span className={`h-2 w-2 rounded-full ${lit ? "bg-[var(--sitch-accent)]" : "bg-white/15"}`} />
              <span className={lit ? "text-white" : "text-white/40"}>{step}</span>
            </li>
          );
        })}
      </ol>

      <button
        onClick={onRun}
        disabled={loading || pendingCount === 0}
        className="mt-4 w-full rounded-lg bg-[var(--sitch-accent)] px-4 py-2 text-sm font-semibold text-black disabled:opacity-40"
      >
        {loading ? "Analyzing interactions…" : `Run learning cycle (${pendingCount})`}
      </button>
      {pendingCount === 0 && !proposal && (
        <p className="mt-2 text-xs text-white/40">
          Give feedback on a response first — that&apos;s what the learning agent analyzes.
        </p>
      )}

      {proposal && (
        <div className="mt-5 space-y-4 border-t border-white/10 pt-4">
          <p className="text-sm text-white/70">{proposal.changeSummary}</p>

          {proposal.patternsDetected.length > 0 && (
            <div>
              <h4 className="text-xs font-semibold uppercase tracking-wide text-white/40">Patterns detected</h4>
              <ul className="mt-2 space-y-2">
                {proposal.patternsDetected.map((p, i) => (
                  <li key={i} className="text-sm">
                    <div className="flex items-center gap-2">
                      <span
                        className={`rounded px-1.5 py-0.5 text-[10px] font-semibold uppercase ${CONFIDENCE_STYLE[p.confidence]}`}
                      >
                        {p.confidence}
                      </span>
                      <span className="font-medium">{p.pattern}</span>
                    </div>
                    <p className="mt-0.5 text-white/50">{p.evidence}</p>
                  </li>
                ))}
              </ul>
            </div>
          )}

          {proposal.usedFallbackHeuristic && (
            <p className="text-xs text-amber-400">
              ⚠ LLM analyst was unreachable — this proposal was generated by Sitch&apos;s heuristic fallback.
            </p>
          )}

          <button
            onClick={onApply}
            disabled={applying}
            className="w-full rounded-lg border border-[var(--sitch-accent)] px-4 py-2 text-sm font-medium text-[var(--sitch-accent)] disabled:opacity-40"
          >
            {applying
              ? "Applying…"
              : proposal.meaningfulChange
              ? "Approve & apply update"
              : "Acknowledge (no change needed)"}
          </button>
        </div>
      )}
    </div>
  );
}
